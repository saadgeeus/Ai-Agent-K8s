# aiops/sop.py
# Responsible for formatting the final diagnosis into a reusable SOP document.
from langchain_community.llms import Ollama
from langchain.prompts import PromptTemplate
from .prompts import SYSTEM_PROMPT, PROMPTS
from .config import MODEL_NAME, OLLAMA_BASE_URL  # Single source of truth
import os
import pathlib

# Absolute path to the docs/ folder — works no matter where you run the script from
DOCS_DIR = pathlib.Path(__file__).parent.parent / "docs"

def generate_sop_document(rca_report: str, filename: str = None) -> str:
    """
    Uses the LLM to convert a raw RCA report into a structured SOP document.

    Args:
        rca_report: The comprehensive output generated by the AIOps Agent.
        filename: The target file path for the SOP. Defaults to docs/sop_report.md

    Returns:
        The content of the newly generated SOP.
    """
    # Default output file — uses absolute path so it always saves in the right place
    if filename is None:
        filename = str(DOCS_DIR / "sop_report.md")
    print("\n✍️ Initiating SOP Documentation Generation...")

    # Use the dedicated SOP prompt
    sop_template = PROMPTS['sop']

    llm = Ollama(
        model=MODEL_NAME,
        base_url=OLLAMA_BASE_URL,
        temperature=0.2 # Slightly higher temperature for more creative/detailed SOP writing
    )

    # The input to the SOP prompt is the RCA report itself
    chain = sop_template | llm

    sop_content = chain.invoke({"rca_report": rca_report})

    # Save the content to the specified file path
    try:
        # Ensure the docs directory exists
        os.makedirs(os.path.dirname(filename), exist_ok=True)

        with open(filename, 'w') as f:
            f.write(sop_content)

        return f"✅ Successfully generated and saved the SOP to: {filename}"

    except Exception as e:
        return f"❌ Error saving SOP document to {filename}: {e}"